import { rm } from "node:fs/promises";

import { appendRuntimeTypeFacades, renderPrimitiveIndex } from "../../primitive-index.js";
import { createTsHeader, writeGeneratedFile } from "../../shared.js";
import type { FrameworkAdapterTargetPrimitivePackageGenerator } from "../types.js";
import { SVELTE_PRIMITIVE_COMPONENTS } from "./inventory.js";

export function createSvelteComponentHeader(generatedBy: string): string {
  return `<!-- Generated by ${generatedBy}. Do not edit by hand. -->\n`;
}

export const generateSveltePrimitivePackage: FrameworkAdapterTargetPrimitivePackageGenerator =
  async ({ components, generatePrimitiveEntries, generatedBy, outputRoot }) => {
    const unsupported = components.find(
      (component) => !SVELTE_PRIMITIVE_COMPONENTS.includes(component as never),
    );
    if (unsupported) {
      throw new Error(
        `Svelte package generation cannot emit unsupported component "${unsupported}".`,
      );
    }
    const componentHeader = createSvelteComponentHeader(generatedBy);
    const moduleHeader = createTsHeader(generatedBy);
    await rm(outputRoot, { force: true, recursive: true });
    await Promise.all([
      generatePrimitiveEntries({ componentHeader, moduleHeader, outputRoot }),
      writeGeneratedFile(
        outputRoot,
        "index.ts",
        renderPrimitiveIndex(moduleHeader, components).replace(
          /from "\.\/([^"/]+)";/g,
          'from "./$1/index.js";',
        ),
      ),
    ]);
    await appendRuntimeTypeFacades(outputRoot, components);
  };
