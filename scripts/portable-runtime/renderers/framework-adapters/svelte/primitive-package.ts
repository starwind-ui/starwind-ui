import { readdir, readFile, rm } from "node:fs/promises";
import path from "node:path";
import { appendRuntimeTypeFacades, renderPrimitiveIndex } from "../../primitive-index.js";
import { createTsHeader, writeGeneratedFile } from "../../shared.js";
import type { FrameworkAdapterTargetPrimitivePackageGenerator } from "../types.js";
import { printSvelteAttachmentExecution } from "./attachment-execution.js";
import { printSvelteFormDiscovery } from "./form-discovery.js";
import { printSvelteFormFieldOwnership } from "./form-field-ownership.js";
import { printSvelteForwardedAttachmentDiscovery } from "./forwarded-attachment-discovery.js";
import { SVELTE_PACKAGE_COMPONENTS, validateSvelteInventory } from "./inventory.js";
import { svelteManualPrimitiveGenerators } from "./manual-primitives.js";
import { printSvelteOverlayCapture } from "./overlay-capture.js";
import {
  printSveltePortalDocumentObserver,
  SVELTE_PORTAL_OBSERVER_COMPONENTS,
} from "./portal-document-observer.js";
import { printSveltePortalPlacement } from "./portal-placement.js";
import { printSvelteRefAttachmentHelper } from "./ref-attachment.js";

export function createSvelteComponentHeader(generatedBy: string): string {
  return `<!-- Generated by ${generatedBy}. Do not edit by hand. -->\n`;
}

export const generateSveltePrimitivePackage: FrameworkAdapterTargetPrimitivePackageGenerator =
  async ({ components, generatePrimitiveEntries, generatedBy, outputRoot }) => {
    validateSvelteInventory(undefined, {
      manualFacades: Object.keys(svelteManualPrimitiveGenerators),
    });
    if (new Set(components).size !== components.length) {
      throw new Error("Svelte package generation received duplicate component identities.");
    }
    const unsupported = components.find(
      (component) => !SVELTE_PACKAGE_COMPONENTS.includes(component as never),
    );
    if (unsupported) {
      throw new Error(
        `Svelte package generation cannot emit unsupported component "${unsupported}".`,
      );
    }
    const componentHeader = createSvelteComponentHeader(generatedBy);
    const moduleHeader = createTsHeader(generatedBy);
    await rm(outputRoot, { force: true, recursive: true });
    await Promise.all([
      generatePrimitiveEntries({ componentHeader, moduleHeader, outputRoot }),
      writeGeneratedFile(
        outputRoot,
        "index.ts",
        renderPrimitiveIndex(moduleHeader, components).replace(
          /from "\.\/([^"/]+)";/g,
          'from "./$1/index.js";',
        ),
      ),
    ]);
    if (components.includes("form") || components.includes("field"))
      await writeGeneratedFile(
        outputRoot,
        "form/FormFieldContext.ts",
        moduleHeader + printSvelteFormFieldOwnership(),
      );
    if (
      components.some((component) => SVELTE_PORTAL_OBSERVER_COMPONENTS.includes(component as never))
    ) {
      await writeGeneratedFile(
        path.join(outputRoot, "_internal"),
        "portal-document-observer.ts",
        moduleHeader + printSveltePortalDocumentObserver(),
      );
      await writeGeneratedFile(
        path.join(outputRoot, "_internal"),
        "portal-placement.ts",
        moduleHeader + printSveltePortalPlacement(),
      );
    }
    const helperImports = await Promise.all(
      (await readdir(outputRoot, { recursive: true }))
        .filter((file) => file.endsWith(".svelte"))
        .map(async (file) => {
          const source = await readFile(path.join(outputRoot, file), "utf8");
          return {
            usesCapture: source.includes('from "../_internal/overlay-capture.js"'),
            usesDiscovery: source.includes(
              'from "../_internal/forwarded-attachment-discovery.js"',
            ),
            usesExecution: source.includes(
              'from "../_internal/attachment-execution.svelte.js"',
            ),
            usesRefAttachment: source.includes('from "../_internal/ref-attachment.js"'),
          };
        }),
    );
    if (helperImports.some((source) => source.usesCapture))
      await writeGeneratedFile(
        path.join(outputRoot, "_internal"),
        "overlay-capture.ts",
        moduleHeader + printSvelteOverlayCapture(),
      );
    if (helperImports.some((source) => source.usesExecution))
      await writeGeneratedFile(
        path.join(outputRoot, "_internal"),
        "attachment-execution.svelte.ts",
        moduleHeader + printSvelteAttachmentExecution(),
      );
    if (helperImports.some((source) => source.usesDiscovery))
      await writeGeneratedFile(
        path.join(outputRoot, "_internal"),
        "forwarded-attachment-discovery.ts",
        moduleHeader + printSvelteForwardedAttachmentDiscovery(),
      );
    if (helperImports.some((source) => source.usesRefAttachment))
      await writeGeneratedFile(
        path.join(outputRoot, "_internal"),
        "ref-attachment.ts",
        moduleHeader + printSvelteRefAttachmentHelper(),
      );
    if (components.includes("input") || components.includes("dropzone"))
      await writeGeneratedFile(
        path.join(outputRoot, "_internal"),
        "form-discovery.ts",
        moduleHeader + printSvelteFormDiscovery(),
      );
    await appendRuntimeTypeFacades(outputRoot, components);
  };
